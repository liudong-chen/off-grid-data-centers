REN4 = json.load(open(f'{B}/Code/OffGrid/scenario_renewable_only/renewable_only_4h_summary.json'))
E, C_ON, MWP, RR, TG = REN4['energy_MWh'], PP['c_on'], PP['MW_pub'], PP['R'], PP['T_GAS']
END = TG + 240; mo = np.arange(END + 1); disc = (1 + RR/12)**(-mo.astype(float))


def ren_flows(rate, T, kind):
    earn = np.zeros(END + 1); cost = np.zeros(END + 1)
    if kind == 'wait':
        b = mo > T; earn[b] = rate*MWP; cost[b] = C_ON*E/12
    else:
        a = (mo > TG) & (mo <= T) if kind == 'hyb' else mo > TG
        earn[mo > TG] = rate*MWP; cost[a] = HR['c_islanded']*E/12
        if kind == 'hyb':
            b = mo > max(T, TG); cost[b] = HR['c_connected_incl_sunk']*E/12
    return (earn*disc).sum()/1e9/20, (cost*disc).sum()/1e9/20


